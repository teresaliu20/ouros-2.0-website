// Encrypts deck media (videos) into public/media/deck/*.enc so they can be served from this public repo.
// Only ciphertext is committed; api/deck.js decrypts for signed-in viewers at /deck?asset=<name>.
//
//   DECK_KEY=<base64 key> node scripts/encrypt-assets.mjs name=/abs/path/file.mp4[:mime] ...
import { createCipheriv, randomBytes, createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync } from "node:fs";

const key = Buffer.from(process.env.DECK_KEY || "", "base64");
if (key.length !== 32) throw new Error("Set DECK_KEY (base64, 32 bytes).");
const outDir = new URL("../public/media/deck/", import.meta.url);
mkdirSync(outDir, { recursive: true });
for (const f of readdirSync(outDir)) if (f.endsWith(".enc")) unlinkSync(new URL(f, outDir));

const map = {};
for (const arg of process.argv.slice(2)) {
  const [name, rest] = arg.split("=");
  const [path, type = "video/mp4"] = rest.split(":");
  const plain = readFileSync(path);
  const hash = createHash("sha256").update(plain).digest("hex").slice(0, 10);
  const iv = randomBytes(12);
  const c = createCipheriv("aes-256-gcm", key, iv);
  const sealed = Buffer.concat([iv, c.update(plain), c.final(), c.getAuthTag()]);
  const file = `${name}-${hash}.enc`;
  writeFileSync(new URL(file, outDir), sealed);
  map[name] = { path: `/media/deck/${file}`, type };
  console.log(`Encrypted ${name}: ${plain.length} bytes -> public/media/deck/${file}`);
}
writeFileSync(
  new URL("../api/_deck-assets.js", import.meta.url),
  `// Generated by scripts/encrypt-assets.mjs. Paths to encrypted deck media (AES-256-GCM, iv prefix).\nexport const ASSETS = ${JSON.stringify(map)};\n`
);
