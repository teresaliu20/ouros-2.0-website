// Encrypts deck-src/index.html into api/_deck-data.js so the deck can live in this public repo.
// The plaintext stays local (deck-src/ is gitignored); only ciphertext is committed.
//
//   DECK_KEY=<base64 key from Vercel> node scripts/encrypt-deck.mjs
//
// Generate a new key (then update DECK_KEY in Vercel and re-run this):
//   node -e "console.log(require('crypto').randomBytes(32).toString('base64'))"
import { createCipheriv, randomBytes } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const keyB64 = process.env.DECK_KEY;
if (!keyB64) throw new Error("Set DECK_KEY (the same base64 value stored in Vercel).");
const key = Buffer.from(keyB64, "base64");
if (key.length !== 32) throw new Error("DECK_KEY must decode to 32 bytes.");

const html = readFileSync(process.argv[2] || new URL("../deck-src/index.html", import.meta.url));
const iv = randomBytes(12);
const cipher = createCipheriv("aes-256-gcm", key, iv);
// Web Crypto (used by the edge function) expects the auth tag appended to the ciphertext.
const sealed = Buffer.concat([cipher.update(html), cipher.final(), cipher.getAuthTag()]);

writeFileSync(
  new URL("../api/_deck-data.js", import.meta.url),
  `// Generated by scripts/encrypt-deck.mjs. Encrypted (AES-256-GCM); unreadable without DECK_KEY.\n` +
    `export const IV = "${iv.toString("base64")}";\n` +
    `export const DATA = "${sealed.toString("base64")}";\n`
);
console.log(`Encrypted ${html.length} bytes → api/_deck-data.js`);
